"""Writes crates/ciplink/src/logix/bundle_data.rs from tools/reference/ciplink_ref/_logix_metadata_bundle.py.

The Rust file holds the same sealed bundle and the three key shares the Python module reconstructs (the shares are
XORed at run time, as in Python). Nothing is decrypted here.
"""

import base64
import os

from fixturelib import ROOT

from ciplink import _logix_metadata_bundle as bundle

OUT = os.path.join(ROOT, "crates", "ciplink", "src", "logix", "bundle_data.rs")


def rust_bytes(data, indent="    "):
    lines = []
    for start in range(0, len(data), 16):
        lines.append(indent + " ".join("0x%02x," % b for b in data[start:start + 16]))
    return "\n".join(lines)


def main():
    sealed = base64.b85decode("".join(bundle._BLOCKS[index] for index in bundle._ORDER))
    parts = [base64.b85decode(value) for value in bundle._MATERIAL]
    assert len(parts) == 3 and all(len(part) == 32 for part in parts)
    text = ["// Generated by tools/fixtures/gen_bundle_data.py from tools/reference/ciplink_ref/_logix_metadata_bundle.py; do not edit.",
            "// Included by bundle.rs. Reversible local obfuscation, not secrecy.",
            "",
            "/// The sealed credential bundle (`LMK1` header, nonce, ciphertext and tag).",
            "const SEALED: [u8; %d] = [" % len(sealed), rust_bytes(sealed), "];", "",
            "/// The three shares whose XOR is the bundle key.",
            "const SHARES: [[u8; 32]; 3] = ["]
    for part in parts:
        text += ["    [", rust_bytes(part, "        "), "    ],"]
    text += ["];", ""]
    with open(OUT, "w", encoding="utf-8", newline="\n") as file:
        file.write("\n".join(text))
    print("wrote", os.path.relpath(OUT, ROOT))


if __name__ == "__main__":
    main()
